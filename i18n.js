const pattern = new RegExp(entries.map(([key]) => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"), "g");

/** 概要: 表示文言を日英で切り替えます。引数: text - 原文、language - ja/en。戻り値: 翻訳済み文字列。 */
export function translateText(text, language) {
  const value = String(text);
  if (language !== "en") return phrases[value.trim()] ? value.replace(value.trim(), phrases[value.trim()]) : value;
  return value.replace(/(\d{4})年度（(\d{4})年(\d+)月期）/g, (_, fy, year, month) => `FY${fy} (year ending ${["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"][Number(month) - 1]} ${year})`)
    .replace(/第([1-4])四半期/g, "Q$1").replace(/(\d+)週/g, "$1 weeks").replace(pattern, (key) => japanese[key])
    .replaceAll("（", " (").replaceAll("）", ")").replaceAll("。", ". ").replaceAll("〜", " – ");
}

/** 概要: 保存済みの言語を取得します。引数: storage - 保存先。戻り値: jaまたはen。 */
export function readLanguage(storage) {
  try { return (storage ?? globalThis.window?.localStorage)?.getItem("earnings-language") === "en" ? "en" : "ja"; } catch { return "ja"; }
}

/** 概要: 言語の選択を保存します。引数: language - ja/en、storage - 保存先。戻り値: なし。 */
export function saveLanguage(language, storage) {
  try { (storage ?? globalThis.window?.localStorage)?.setItem("earnings-language", language === "en" ? "en" : "ja"); } catch { /* 保存できなくても画面の切替は継続します。 */ }
}
